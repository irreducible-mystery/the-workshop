#!/bin/sh
# ---------------------------------------------------------------------------
# THE WORKSHOP -> LEAN.  Ledger-as-view: render, and refuse to drift.
#
# WHY THIS EXISTS (round 5, builder findings E2 + the Q6 mechanism fix).
#
# Round 4's PROOFS.md reproduced the compile transcript's measurements to the
# millisecond and every hash -- and got the DATE wrong.  (The artifacts read
# 06:54:40Z vs 07:12Z: seventeen minutes twenty seconds.  An earlier version of
# this comment said "twelve minutes" -- the 12 lifted from the token 07:12
# rather than computed from the two halves.  Builder finding F4, and a tidy
# specimen: every noun in that sentence resolved.)
# Exactly one field in that block was regenerated by hand at writing time; it
# is the only field that was wrong.  That is the whole diagnosis in one block:
# copied tokens were right, emitted tokens were not, and the register with no
# execution date is the one where the author is the only adjudicator.
#
# The fix is not to try harder.  It is to remove the author from the token
# register: blocks of the ledger that state counts, names, dates or hashes are
# VIEWS, rendered from instrument output, never typed.  Prose points at them
# and does not restate them.
#
# A view has two failure modes and this script instruments both:
#   (1) A VIEW OF THE WRONG THING -- faithfully rendered, unverifiably
#       relevant.  Closed by E5(ii): both instruments now stamp the SHA-256 of
#       every source they measured into their own output, and `check` below
#       requires those stamps to match the working tree.
#   (2) SILENT STALENESS -- the block is a true rendering of an old run.
#       Closed by `check`, which diffs the ledger block against the instrument
#       output and exits nonzero on any drift.  Same shape as ship.sh's STALE
#       check, one layer up.
#
# Usage:
#   sh audit/views.sh render   -- rewrite the VIEW blocks in PROOFS.md
#   sh audit/views.sh check    -- verify they match; exit 1 if not (for CI/ship)
#
# A view block in PROOFS.md is delimited by:
#   <!-- VIEW:<name> BEGIN - rendered by audit/views.sh, do not edit by hand -->
#   ...content...
#   <!-- VIEW:<name> END -->
# ---------------------------------------------------------------------------
set -u

MODE="${1:-check}"
LEDGER=PROOFS.md
TR=audit/transcript-round8.txt
AX=audit/axioms-round8.txt

[ -f "$LEDGER" ] || { echo "no $LEDGER here -- run from workshop/lean/"; exit 1; }

fail=0

# --- extract a view's content from PROOFS.md --------------------------------
ledger_block() {
  awk -v n="$1" '
    $0 ~ ("<!-- VIEW:" n " BEGIN") { inb = 1; next }
    $0 ~ ("<!-- VIEW:" n " END")   { inb = 0 }
    inb { print }
  ' "$LEDGER"
}

# --- render a view from its instrument --------------------------------------
# transcript: the source-hash stanza, the per-file stanza, and the totals.
render_transcript() {
  [ -f "$TR" ] || { echo "(instrument output $TR not present)"; return; }
  echo '```'
  sed -n '/^date /,/^RESULT/p' "$TR"
  echo '```'
}

render_axioms() {
  [ -f "$AX" ] || { echo "(instrument output $AX not present)"; return; }
  echo '```'
  sed -n '/^file  /,/^  Classical.choice/p' "$AX"
  echo '```'
}

VIEWS="transcript axioms"

if [ "$MODE" = "render" ]; then
  # The backup goes to the scratch dir, NOT beside the ledger.  Round 6 shipped
  # a `PROOFS.md.bak` stowaway because render left it in the tree and ship.sh
  # (REQUIRED-only) structurally could not police an extra file (builder's
  # round-7 ferry note).  Keeping the backup out of the tree removes the
  # stowaway at its source; ship.sh's enumerate-or-forbid is the belt to this
  # brace.
  bak="/tmp/$(basename "$LEDGER").bak.$$"
  cp "$LEDGER" "$bak"
  for v in $VIEWS; do
    tmp=$(mktemp)
    "render_$v" > "$tmp"
    awk -v n="$v" -v f="$tmp" '
      $0 ~ ("<!-- VIEW:" n " BEGIN") { print; while ((getline l < f) > 0) print l; skip = 1; next }
      $0 ~ ("<!-- VIEW:" n " END")   { skip = 0 }
      !skip { print }
    ' "$LEDGER" > "$LEDGER.new" && mv "$LEDGER.new" "$LEDGER"
    rm -f "$tmp"
    echo "rendered VIEW:$v"
  done
  echo "done -- previous ledger backed up out-of-tree at $bak"
  exit 0
fi

# --- check mode --------------------------------------------------------------
echo "=============================================================="
echo " LEDGER-AS-VIEW -- checking generated blocks against instruments"
echo "=============================================================="

for v in $VIEWS; do
  if ! grep -q "<!-- VIEW:$v BEGIN" "$LEDGER"; then
    printf '  ABSENT   VIEW:%s  (no such block in %s)\n' "$v" "$LEDGER"; fail=1; continue
  fi
  a=$(ledger_block "$v" | sha256sum | cut -c1-64)
  b=$("render_$v"      | sha256sum | cut -c1-64)
  if [ "$a" = "$b" ]; then
    printf '  ok       VIEW:%s\n' "$v"
  else
    printf '  DRIFTED  VIEW:%s  (ledger %s... vs instrument %s...)\n' \
           "$v" "$(echo "$a" | cut -c1-12)" "$(echo "$b" | cut -c1-12)"
    fail=1
  fi
done

# --- failure mode (1): is the instrument output about THESE sources? ---------
echo
echo "--------------------------------------------------------------"
echo " do the instrument outputs describe the CURRENT sources?"
echo " (E5(ii) -- a view of the wrong thing is the other failure mode)"
echo "--------------------------------------------------------------"
for f in $(cat audit/sources.txt) lean-toolchain; do
  th=$(sha256sum "$f" | cut -c1-64)
  hit=0
  for out in "$TR" "$AX"; do
    [ -f "$out" ] || continue
    if grep -q "$th" "$out"; then hit=$((hit+1)); fi
  done
  if [ "$hit" -eq 2 ]; then
    printf '  ok       %-20s stamped in both outputs\n' "$f"
  else
    printf '  MISMATCH %-20s stamped in %d/2 outputs (tree hash %s...)\n' \
           "$f" "$hit" "$(echo "$th" | cut -c1-12)"
    fail=1
  fi
done

echo
if [ "$fail" -eq 0 ]; then
  echo "RESULT: every view matches its instrument, and every instrument"
  echo "        measured the sources now in the tree.  PASS."
else
  echo "RESULT: FAIL -- a view has drifted, or describes sources that are"
  echo "        no longer here.  Run 'sh audit/views.sh render' after"
  echo "        re-running the instruments."
fi
exit $fail
